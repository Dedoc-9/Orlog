"""Rebuilds generated C programs with UBSan in trap mode and runs them; a trap is undefined behaviour.

  python -B ubsan.py [LIMIT]
Uses the C sources the fuzz campaign left in work/fuzz/w/cache (generated by the C backend, unchanged).
"""
import glob
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
FLAGS = ["-std=c99", "-O1", "-ffp-contract=off", "-fno-fast-math", "-w",
         "-fsanitize=undefined", "-fsanitize-trap=undefined", "-fno-sanitize-recover=all"]


def main():
    limit = int(sys.argv[1]) if len(sys.argv) > 1 else 300
    srcs = sorted(glob.glob(os.path.join(HERE, "work", "fuzz", "w", "cache", "c99-*.c")))[:limit]
    out = os.path.join(HERE, "work", "ubsan")
    os.makedirs(out, exist_ok=True)
    traps, built, ran = [], 0, 0
    for s in srcs:
        exe = os.path.join(out, os.path.basename(s)[:-2] + "-ubsan.exe")
        r = subprocess.run(["clang"] + FLAGS + [s, "-o", exe], capture_output=True, text=True)
        if r.returncode != 0:
            print("BUILD FAILED", s, r.stderr[-300:])
            continue
        built += 1
        p = subprocess.run([exe, os.path.join(out, "u.out"), os.path.join(out, "u.receipt")], capture_output=True)
        ran += 1
        if p.returncode not in (0,):
            traps.append((s, p.returncode))
            print("NONZERO EXIT", p.returncode, s, p.stderr[-200:])
    print("UBSAN: %d built, %d ran, %d non-zero exits" % (built, ran, len(traps)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
